"""SimInterface: the contract that both Sim and FakeSim satisfy (api-spec §5.2).

``sim_bridge`` depends on this Protocol, never on ``Sim`` directly, so the same
node runs against CoppeliaSim in lab and against FakeSim in tests. This is the
L4 pattern (a Protocol plus a fake), applied to the course's own code.
"""

from __future__ import annotations

from typing import Protocol, runtime_checkable

from .robot import Handles


@runtime_checkable
class SimInterface(Protocol):
    def handles_from_yaml(self, path: str) -> Handles: ...
    def start(self, stepping: bool = False) -> None: ...
    def is_running(self) -> bool: ...
    def read_line_sensors(self, handles: tuple[int, ...]) -> tuple[float, ...]: ...
    def read_proximity(self, handle: int | None) -> tuple[bool, float]: ...
    def set_wheel_speeds(self, left: int, right: int, left_rad_s: float, right_rad_s: float) -> None: ...
    def get_pose2d(self, handle: int) -> tuple[float, float, float]: ...
    def time(self) -> float: ...
    def step(self) -> None: ...
    def stop(self) -> None: ...
    def close(self) -> None: ...
